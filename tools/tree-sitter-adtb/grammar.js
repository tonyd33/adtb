/// <reference types="tree-sitter-cli/dsl" />

const RESERVED = [
  'and', 'bundle', 'by', 'check', 'constraint', 'delete', 'else', 'exists', 'fail', 'false', 'fix',
  'fn', 'for', 'from', 'group', 'if', 'import', 'in', 'insert', 'into', 'key', 'let', 'match',
  'module', 'not', 'or', 'order', 'ordered', 'query', 'relation', 'return', 'schema', 'select',
  'set', 'skip', 'temp', 'then', 'top', 'transact', 'true', 'try', 'txn', 'type', 'union', 'update',
  'where', 'with',
];

// Each word's scanner entry decides from its following token whether it is a keyword here.
// Keep the order equal to the scanner's symbol enum.
const CONTEXTUAL = [
  'add', 'drop', 'rename', 'remove', 'split', 'merge', 'nest', 'unnest', 'move', 'alter', 'rekey',
  'define', 'redefine', 'unstore', 'uninstall', 'install', 'enable', 'disable', 'deprecate',
  'revert', 'script', 'adopt', 'grant', 'revoke', 'store', 'feed', 'aggregate', 'explain', 'pin',
  'unpin', 'cancel', 'terminate', 'vacuum', 'verify', 'reindex', 'compact', 'finalize', 'retire',
  'supersede', 'export', 'register', 'apply', 'print', 'archive', 'rotate', 'destroy', 'dump',
  'restore', 'backup', 'create', 'map', 'unmap', 'take', 'after', 'desc', 'asc', 'generate',
  'unique', 'interval', 'index', 'volatile', 'default', 'computed', 'lease', 'priority', 'budget',
  'hide', 'catalog', 'deterministic', 'arm', 'joins', 'before', 'carry', 'fill', 'retry',
  'read_only', 'deferrable', 'durability', 'unless', 'rejects', 'pins', 'sums', 'online', 'offline',
  'incremental', 'encrypt', 'wasm', 'host', 'on_delete', 'to', 'at', 'reject', 'at_restore',
  'default_generate', 'insert_from', 'exists_where', 'order', 'analyze',
];

const SPELLING = {
  on_delete: 'on', at_restore: 'at', default_generate: 'generate', insert_from: 'from',
  exists_where: 'where',
};

const k = ($, word) => seq($[`_kw_${word}`], SPELLING[word] ?? word);
const expr = ($, name, level = '_expression') => (name ? seq(field(name, $[level]), $._end) : seq($[level], $._end));
const commaSep1 = (rule) => seq(rule, repeat(seq(',', rule)));
const commaSep = (rule) => optional(commaSep1(rule));

const PREC = { shift: 20 };

module.exports = grammar({
  name: 'adtb',

  word: ($) => $.lower,

  reserved: {
    global: () => RESERVED,
  },

  extras: ($) => [/[ \t\r\n]/, $.comment],

  externals: ($) => [
    ...CONTEXTUAL.map((w) => $[`_kw_${w}`]),
    $._type_arg,
    $._verify_target,
    $._anon_first,
    $._anon_next,
    $._prelude_record,
    $._call_lparen,
    $._tcall_lparen,
    $._keys_lparen,
    $._gen_comma,
    $._ctor_dot,
    $._tcall_dot,
    $._key_dot,
    $._field_call_bad,
    $._elision_dot,
    $._ctor_lbrace,
    $._midline_bad,
    $._never,
    $._end,
    $._union_op,
    $._or_op,
    $._and_op,
    $._cmp_op,
    $._add_op,
    $._mul_op,
    $._field_dot,
    $._selection_dot,
    $._backlink_dot,
    $._arm_bar,
    $._qualifier,
    $._text_more,
    $._record_elision,
    $._field_colon,
    $.wildcard,
    $.int,
    $.decimal,
    $.float,
    $.duration,
    $.migration,
    $.hash,
    $.bundle_name,
    $.family_name,
    $._refused,
  ],


  rules: {
    source_file: ($) => repeat(choice($._item, seq($._midline_bad, $._never))),

    _item: ($) => choice(
      $.module_header,
      $.bundle_header,
      $.import,
      $.type_declaration,
      $.relation_declaration,
      $.set_declaration,
      $.function_declaration,
      $.query_declaration,
      $.transaction_declaration,
      $.constraint_declaration,
      $.check_declaration,
      $.store_declaration,
      $.aggregate_declaration,
      $.feed_declaration,
      $._operator,
      $.transact_block,
      $.temp_declaration,
      $.set_setting,
      $.grant,
      $.revoke,
      $.role_statement,
      $.peer_statement,
      $._command,
      $._write,
      expr($),
    ),

    comment: () => token(seq('--', /.*/)),
    text: () => token(seq(
      '"',
      repeat(choice(
        /[^"\\\n]/,
        /\\["\\nrt]/,
        // A \u{...} escape names one Unicode scalar value.
        /\\u\{0*([0-9a-fA-F]{1,3}|[0-9a-cA-CeEfF][0-9a-fA-F]{3}|[dD][0-7][0-9a-fA-F]{2}|[1-9a-fA-F][0-9a-fA-F]{4}|10[0-9a-fA-F]{4})\}/,
      )),
      '"',
    )),
    lower: () => /[a-z][A-Za-z0-9_]*/,
    upper: () => /[A-Z][A-Za-z0-9_]*/,

    _field_word: ($) => choice($.lower, ...RESERVED),
    field_name: ($) => $._field_word,
    _reserved_field: () => prec(PREC.shift, choice(...RESERVED)),

    qualified_lower: ($) => seq(field('module', $.lower), $._qualifier, '::', field('name', $.lower)),
    qualified_upper: ($) => seq(field('module', $.lower), $._qualifier, '::', field('name', $.upper)),
    _qlower: ($) => choice($.lower, $.qualified_lower),
    _qupper: ($) => choice($.upper, $.qualified_upper),

    ctor_selection: ($) => choice($.upper, seq('(', $.upper, repeat(seq('|', $.upper)), ')')),
    relation_ref: ($) => prec.right(seq(
      field('relation', $._qlower),
      optional(seq('.', field('selection', $.ctor_selection))),
    )),
    ctor_path: ($) => seq(field('type', $._qupper), '.', field('constructor', $.upper)),
    field_path: ($) => seq(
      field('type', $._qupper),
      '.',
      optional(seq(field('constructor', $.upper), '.')),
      field('field', $.field_name),
    ),
    default_path: ($) => seq(
      field('relation', $._qlower),
      '.',
      optional(seq(field('constructor', $.upper), '.')),
      field('field', $.field_name),
    ),
    version: ($) => seq(field('number', $.int), '(', field('hash', $.hash), ')'),

    module_header: ($) => seq('module', field('name', $.lower)),

    bundle_header: ($) => prec.right(seq(
      'bundle',
      field('name', $.bundle_name),
      'pins',
      field('pins', $.version),
      optional(seq(k($, 'catalog'), field('catalog', $.version))),
      'edition',
      field('edition', $.text),
      repeat($._header_clause),
    )),
    _header_clause: ($) => choice(
      seq(k($, 'lease'), expr($, 'lease', '_prefix_e')),
      seq(k($, 'priority'), field('priority', $.lower)),
      seq(k($, 'budget'), field('budget', $.record_expression)),
      seq(k($, 'hide'), 'new', 'constructors'),
    ),

    import: ($) => seq('import', choice(seq('fn', field('function', $._qlower)), field('module', $.lower))),

    _type: ($) => choice($.function_type, $._sum_type),
    function_type: ($) => seq(field('parameter', $._sum_type), '->', field('result', $._type)),
    _sum_type: ($) => choice($.sum_type, $._app_type),
    sum_type: ($) => seq(
      $._anon_first,
      $.anonymous_constructor,
      repeat(seq('|', $._anon_next, $.anonymous_constructor)),
    ),
    anonymous_constructor: ($) => seq(field('name', $.upper), optional(seq($._ctor_lbrace, field('record', $.record_type)))),
    _app_type: ($) => choice(
      $.type_application,
      $.type_selection,
      $.key_type,
      $.type_variable,
      $.unit_type,
      $.record_type,
      $._named_type,
      $._paren_type,
    ),
    _named_type: ($) => alias($._qupper, $.type_name),
    type_application: ($) => choice(
      seq(field('name', $._named_type), repeat1(seq($._type_arg, field('argument', $._type_argument)))),
      seq($._paren_type, repeat1(seq($._type_arg, field('argument', $._type_argument)))),
      seq($._prelude_record, field('name', alias($.upper, $.type_name)), field('argument', $.record_type), repeat(seq($._type_arg, field('argument', $._type_argument)))),
    ),
    type_selection: ($) => seq(field('name', $._named_type), '.', field('selection', $.ctor_selection)),
    key_type: ($) => seq('Key', field('relation', $.relation_ref)),
    type_variable: ($) => $.lower,
    unit_type: () => seq('(', ')'),
    _paren_type: ($) => seq('(', $._type, ')'),
    _type_argument: ($) => choice(
      $.int,
      $.type_selection,
      $.key_type,
      $.type_variable,
      $.unit_type,
      $._named_type,
      $._paren_type,
    ),
    record_type: ($) => seq('{', commaSep($.field_type), '}'),
    field_type: ($) => seq(
      field('name', $.field_name),
      ':',
      field('type', $._type),
      optional($.on_delete),
    ),
    on_delete: ($) => seq(k($, 'on_delete'), 'delete', field('action', $._ref_action)),
    _ref_action: ($) => choice('restrict', 'cascade', 'clear', $.retag_action),
    retag_action: ($) => prec.right(seq('retag', field('constructor', $.upper), optional(seq($._ctor_lbrace, field('record', $.record_expression))))),
    parameters: ($) => seq('(', commaSep($.parameter), ')'),
    parameter: ($) => seq(field('name', $.lower), ':', field('type', $._type)),

    type_declaration: ($) => seq(
      'type',
      field('name', $.upper),
      repeat(field('parameter', $.lower)),
      optional('ordered'),
      optional(field('header', $.record_type)),
      '=',
      field('body', choice($.newtype_body, $.record_type, $.constructors)),
    ),
    newtype_body: ($) => prec.right(seq('new', field('type', $._app_type), optional(seq('where', expr($, 'domain'))))),
    constructors: ($) => seq($.constructor_definition, repeat(seq('|', $.constructor_definition))),
    constructor_definition: ($) => prec.right(seq(field('name', $.upper), optional(seq($._ctor_lbrace, field('record', $.record_type))))),

    relation_declaration: ($) => prec.right(seq(
      'relation',
      field('name', $._qlower),
      ':',
      field('type', $._app_type),
      repeat($._relation_clause),
    )),
    _relation_clause: ($) => choice(
      $.key_clause,
      $.unique_clause,
      $.index_clause,
      alias($._volatile, $.volatile_clause),
      $.default_clause,
      $.computed_clause,
    ),
    _volatile: ($) => k($, 'volatile'),
    _key_fields: ($) => choice($.field_name, seq('(', commaSep1($.field_name), ')')),
    key_clause: ($) => prec.right(seq('key', field('fields', $._key_fields), optional($.generated))),
    generated: ($) => seq(k($, 'generate'), field('generator', $.lower)),
    store_key_clause: ($) => seq('key', field('fields', $._key_fields)),
    unique_clause: ($) => prec.right(seq(k($, 'unique'), $.index_fields, optional($.scope))),
    index_clause: ($) => prec.right(seq(optional(k($, 'interval')), k($, 'index'), $.index_fields, optional($.scope))),
    scope: ($) => seq('in', $.ctor_selection),
    index_fields: ($) => seq('(', commaSep1(choice(alias($._reserved_field, $.field_name), expr($))), ')'),
    default_clause: ($) => seq(
      k($, 'default'),
      optional(seq(field('constructor', $.upper), '.')),
      field('field', $.field_name),
      '=',
      field('value', $._default_value),
    ),
    _default_value: ($) => choice($.generated_default, expr($)),
    generated_default: ($) => seq(k($, 'default_generate'), field('generator', $.lower)),
    computed_clause: ($) => seq(k($, 'computed'), field('field', $.lower), ':', field('type', $._type), '=', expr($, 'value')),

    set_declaration: ($) => seq(
      'set',
      field('name', $.upper),
      'of',
      field('relation', $.lower),
      '=',
      field('member', $.upper),
      repeat(seq('|', field('member', $.upper))),
    ),

    function_declaration: ($) => seq(
      'fn',
      field('name', $.lower),
      optional(field('type_parameters', $.type_parameters)),
      field('parameters', $.parameters),
      '->',
      field('result', $._type),
      '=',
      choice(field('body', choice($.wasm_body, $.host_body)), expr($, 'body')),
    ),
    type_parameters: ($) => seq('[', commaSep1($.type_parameter), ']'),
    type_parameter: ($) => seq(field('name', $.lower), optional(seq(':', field('bound', $.upper), repeat(seq('+', field('bound', $.upper)))))),
    wasm_body: ($) => seq(k($, 'wasm'), field('module', $.text), 'export', field('export', $.text)),
    host_body: ($) => prec.right(seq(k($, 'host'), field('name', $.text), 'version', field('version', $.text), optional(k($, 'deterministic')))),

    limit_clause: ($) => seq('limit', expr($, 'limit', '_prefix_e')),
    query_declaration: ($) => seq(
      'query',
      field('name', $.lower),
      field('parameters', $.parameters),
      optional($.limit_clause),
      '->',
      field('result', $._type),
      '=',
      expr($, 'body'),
    ),
    transaction_declaration: ($) => seq(
      'txn',
      field('name', $.lower),
      field('parameters', $.parameters),
      optional($.limit_clause),
      '->',
      field('result', $._type),
      '=',
      field('body', choice($.elision, $.transact_block)),
    ),
    constraint_declaration: ($) => seq('constraint', field('name', $.lower), '=', expr($, 'query')),
    check_declaration: ($) => seq(
      'check',
      field('name', $.lower),
      'on',
      field('on', $.relation_ref),
      '(',
      expr($, 'predicate'),
      ')',
    ),
    store_declaration: ($) => prec.right(seq(
      k($, 'store'),
      field('view', $._qlower),
      repeat(choice($.store_key_clause, $.unique_clause, $.index_clause)),
    )),
    feed_declaration: ($) => seq(k($, 'feed'), field('name', $.lower), 'of', field('of', $.relation_ref)),
    aggregate_declaration: ($) => seq(
      k($, 'aggregate'),
      field('name', $.lower),
      field('parameters', $.parameters),
      '->',
      field('result', $._type),
      '=',
      'state',
      field('state', $.record_type),
      'init',
      expr($, 'init'),
      'step',
      $._two_binders,
      expr($, 'step'),
      'merge',
      $._two_binders,
      expr($, 'merge'),
      'finish',
      field('binder', $.lower),
      '->',
      expr($, 'finish'),
    ),
    _two_binders: ($) => seq('(', field('binder', $.lower), ',', field('binder', $.lower), ')', '->'),

    _operator: ($) => choice(
      $.add_operator,
      $.drop_operator,
      $.rename_operator,
      $.remove_operator,
      $.split_operator,
      $.merge_operator,
      $.nest_operator,
      $.unnest_operator,
      $.alter_operator,
      $.move_operator,
      $.rekey_operator,
      $.define_operator,
      $.redefine_operator,
      $.unstore_operator,
      $.state_operator,
      $.revert_operator,
      $.script_operator,
      $.install_operator,
      $.uninstall_operator,
      $.adopt_operator,
    ),
    add_operator: ($) => seq(k($, 'add'), choice(
      seq('module', field('module', $.lower)),
      $.type_declaration,
      $.relation_declaration,
      $.set_declaration,
      $.constraint_declaration,
      $.check_declaration,
      $.add_constructor,
      $.add_field,
      seq(k($, 'unique'), $.index_fields, 'in', field('on', $.relation_ref)),
      seq(optional(k($, 'interval')), k($, 'index'), $.index_fields, 'in', field('on', $.relation_ref)),
      seq(k($, 'default'), field('path', $.default_path), '=', field('value', $._default_value)),
      seq(k($, 'computed'), $._computed_definition),
    )),
    add_constructor: ($) => prec.right(seq(
      'constructor',
      field('path', $.ctor_path),
      optional(seq($._ctor_lbrace, field('record', $.record_type))),
      optional(choice(seq(k($, 'before'), field('before', $.upper)), seq(k($, 'after'), field('after', $.upper)))),
      repeat(choice($.joins_clause, $.arm_clause)),
    )),
    joins_clause: ($) => prec.right(seq(k($, 'joins'), commaSep1($.relation_ref))),
    arm_clause: ($) => seq(
      k($, 'arm'),
      field('target', $._qlower),
      optional(seq('.', field('field', $.lower))),
      ':',
      field('pattern', $._pattern),
      '->',
      expr($, 'body'),
    ),
    add_field: ($) => seq(
      'field',
      field('path', $.field_path),
      ':',
      field('type', $._type),
      optional($.on_delete),
      $.fill,
    ),
    fill: ($) => seq(k($, 'fill'), $._fill_value),
    _fill_value: ($) => choice($.fill_match, expr($)),
    fill_match: ($) => prec.right(seq('match', $._arms)),
    _computed_definition: ($) => seq(
      field('relation', $._qlower),
      '.',
      field('field', $.lower),
      ':',
      field('type', $._type),
      '=',
      expr($, 'value'),
    ),
    drop_operator: ($) => seq(k($, 'drop'), choice(
      seq('module', field('module', $.lower)),
      seq('type', field('type', $._qupper)),
      seq('relation', field('relation', $._qlower)),
      seq('set', field('set', $.upper), 'of', field('relation', $._qlower)),
      seq('fn', field('function', $._qlower)),
      seq('constraint', field('constraint', $._qlower)),
      seq('check', field('check', $._qlower)),
      seq('field', field('path', $.field_path)),
      seq(k($, 'unique'), $.index_fields, 'in', field('on', $.relation_ref)),
      seq(optional(k($, 'interval')), k($, 'index'), $.index_fields, 'in', field('on', $.relation_ref)),
      seq(k($, 'default'), field('path', $.default_path)),
      seq(k($, 'computed'), field('relation', $._qlower), '.', field('field', $.lower)),
      seq(k($, 'aggregate'), field('aggregate', $._qlower)),
    )),
    rename_operator: ($) => seq(k($, 'rename'), choice(
      seq('type', field('from', $._qupper), 'to', field('to', $.upper)),
      seq('relation', field('from', $._qlower), 'to', field('to', $.lower)),
      seq('set', field('from', $.upper), 'of', field('relation', $._qlower), 'to', field('to', $.upper)),
      seq('constructor', field('from', $.ctor_path), 'to', field('to', $.upper)),
      seq('field', field('from', $.field_path), 'to', field('to', $.field_name)),
    )),
    remove_operator: ($) => seq(k($, 'remove'), 'constructor', field('path', $.ctor_path)),
    split_operator: ($) => prec.right(seq(
      k($, 'split'),
      'constructor',
      field('path', $.ctor_path),
      'into',
      $.constructor_definition,
      repeat(seq('|', $.constructor_definition)),
      'by',
      'match',
      $._arms,
      repeat(choice(
        seq(k($, 'unique'), $.index_fields, $.scope),
        seq(optional(k($, 'interval')), k($, 'index'), $.index_fields, $.scope),
        $.arm_clause,
      )),
    )),
    _ctor_set_path: ($) => seq(field('type', $._qupper), '.', field('selection', $.ctor_selection)),
    merge_operator: ($) => prec.right(seq(
      k($, 'merge'),
      'constructor',
      $._ctor_set_path,
      'into',
      $.constructor_definition,
      optional(seq('by', 'match', $._arms)),
      repeat($.arm_clause),
    )),
    nest_operator: ($) => prec.right(seq(
      k($, 'nest'),
      'constructor',
      $._ctor_set_path,
      'into',
      $.constructor_definition,
      repeat($.arm_clause),
    )),
    unnest_operator: ($) => prec.right(seq(k($, 'unnest'), 'constructor', field('path', $.ctor_path), repeat($.arm_clause))),
    alter_operator: ($) => seq(k($, 'alter'), 'field', field('path', $.field_path), k($, 'on_delete'), 'delete', field('action', $._ref_action)),
    move_operator: ($) => prec.right(seq(
      k($, 'move'),
      'field',
      field('path', $.field_path),
      'to',
      field('to', $._qupper),
      optional(seq('.', field('selection', $.ctor_selection))),
      optional($.fill),
    )),
    rekey_operator: ($) => prec.right(seq(
      k($, 'rekey'),
      'relation',
      field('relation', $._qlower),
      'key',
      field('key', $._key_fields),
      optional(seq(k($, 'carry'), commaSep1($.field_path))),
    )),
    define_operator: ($) => seq(k($, 'define'), choice($.aggregate_declaration, $.function_declaration)),
    redefine_operator: ($) => seq(k($, 'redefine'), choice(seq(k($, 'computed'), $._computed_definition), $.function_declaration)),
    unstore_operator: ($) => seq(k($, 'unstore'), field('view', $._qlower)),
    state_operator: ($) => seq(choice(k($, 'enable'), k($, 'disable'), k($, 'deprecate')), field('target', choice($.ctor_path, $.relation_ref))),
    revert_operator: ($) => prec.right(seq(k($, 'revert'), field('migration', $.migration), repeat($.revert_fill))),
    revert_fill: ($) => seq(k($, 'fill'), field('path', $.field_path), '=', $._fill_value),
    script_operator: ($) => seq(k($, 'script'), $._write),
    install_operator: ($) => seq(k($, 'install'), field('name', $.lower), field('version', $.text), 'from', field('from', $.text)),
    uninstall_operator: ($) => seq(k($, 'uninstall'), field('name', $.lower)),
    adopt_operator: ($) => seq(k($, 'adopt'), 'tzdb', field('release', $.text), 'from', field('from', $.text)),

    grant: ($) => prec.right(seq(
      k($, 'grant'),
      commaSep1($._privilege),
      k($, 'to'),
      field('to', $.lower),
      optional(seq('with', 'grant', 'option')),
    )),
    revoke: ($) => seq(k($, 'revoke'), commaSep1($._privilege), 'from', field('from', $.lower)),
    _privilege: ($) => choice(
      $.table_privilege,
      $.retag_privilege,
      $.call_privilege,
      alias(choice('schema', 'adhoc', 'assert', 'monitor', 'cancel', 'maintain', 'configure', 'read_files', 'write_files'), $.capability),
    ),
    table_privilege: ($) => prec.right(choice(
      seq('insert', field('relation', $.relation_ref)),
      seq('delete', field('relation', $.relation_ref)),
      seq(choice('update', 'read'), field('relation', $.relation_ref), optional($.grant_fields)),
    )),
    grant_fields: ($) => seq(optional('frozen'), '(', commaSep1($.grant_field), ')'),
    grant_field: ($) => seq(optional(seq(field('constructor', $.upper), '.')), field('name', $.field_name)),
    retag_privilege: ($) => prec.right(seq(
      'retag',
      field('from', $.relation_ref),
      '->',
      field('to', $.relation_ref),
      optional(seq('except', '(', commaSep1($.retag_pair), ')')),
    )),
    retag_pair: ($) => seq(field('from', $.upper), '->', field('to', $.upper)),
    call_privilege: ($) => prec.right(seq('call', choice(
      seq('fn', field('function', $._qlower)),
      seq(field('bundle', $.bundle_name), optional(seq('::', field('query', $.lower)))),
      seq(field('family', $.family_name), optional(seq('::', field('query', $.lower), optional($.call_signature)))),
    ))),
    call_signature: ($) => seq('at', field('at', $.int), field('parameters', $.parameters), '->', field('result', $._type)),

    role_statement: ($) => choice(
      seq(k($, 'create'), 'role', field('role', $.lower)),
      seq(k($, 'drop'), 'role', field('role', $.lower)),
      seq(k($, 'alter'), 'role', field('role', $.lower), 'password', expr($, 'password', '_prefix_e')),
    ),
    peer_statement: ($) => choice(
      seq(k($, 'map'), 'peer', field('pattern', $.text), 'on', field('listener', $.lower), 'to', field('role', $.lower)),
      seq(k($, 'unmap'), 'peer', field('ordinal', $.int), 'on', field('listener', $.lower)),
    ),

    temp_declaration: ($) => prec.right(seq(
      'temp',
      'relation',
      field('name', $.lower),
      ':',
      field('type', $._app_type),
      optional(seq('key', field('key', $._key_fields), optional($.generated))),
    )),
    set_setting: ($) => seq('set', 'setting', field('name', $.upper), '=', expr($, 'value')),

    _command: ($) => choice(
      $.explain_command,
      $.plan_command,
      $.call_command,
      $.session_command,
      $.vacuum_command,
      $.verify_command,
      $.reindex_command,
      $.compact_command,
      $.finalize_command,
      $.bundle_command,
      $.export_command,
      $.migrations_command,
      $.print_command,
      $.archive_command,
      $.key_command,
      $.dump_command,
      $.restore_command,
      $.backup_command,
    ),
    explain_command: ($) => seq(k($, 'explain'), optional(k($, 'analyze')), choice(
      field('target', choice($.registered_target, $.transact_block, $._plain_write)),
      expr($, 'target'),
    )),
    registered_target: ($) => seq(field('bundle', $.bundle_name), '::', field('query', $.lower), $._call_lparen_any, $._call_body),
    _call_lparen_any: ($) => choice('(', seq($._call_lparen, '(')),
    plan_command: ($) => seq(choice(k($, 'pin'), k($, 'unpin')), 'plan', expr($, 'id', '_prefix_e')),
    call_command: ($) => seq(k($, 'cancel'), 'call', expr($, 'id', '_prefix_e')),
    session_command: ($) => seq(k($, 'terminate'), 'session', expr($, 'id', '_prefix_e')),
    vacuum_command: ($) => seq(k($, 'vacuum'), field('relation', $._qlower)),
    verify_command: ($) => prec.right(seq(k($, 'verify'), optional(seq($._verify_target, field('relation', $._qlower))))),
    reindex_command: ($) => prec.right(seq(
      k($, 'reindex'),
      field('relation', $._qlower),
      optional(seq(k($, 'index'), $.index_fields, optional($.scope))),
      optional(choice(k($, 'online'), k($, 'offline'))),
    )),
    compact_command: ($) => k($, 'compact'),
    finalize_command: ($) => seq(k($, 'finalize'), 'upgrade'),
    bundle_command: ($) => choice(
      seq(k($, 'retire'), 'bundle', field('name', $.bundle_name)),
      seq(k($, 'supersede'), 'bundle', field('name', $.bundle_name), 'by', field('by', $.bundle_name)),
      seq(k($, 'register'), 'bundle', field('path', $.text)),
    ),
    export_command: ($) => prec.right(seq(
      k($, 'export'),
      expr($, 'source', '_or_e'),
      'to',
      field('path', $.text),
      optional(seq(k($, 'sums'), 'text')),
    )),
    migrations_command: ($) => prec.right(seq(k($, 'apply'), 'migrations', field('path', $.text), repeat(seq($._text_more, field('path', $.text))))),
    print_command: ($) => seq(k($, 'print'), 'schema'),
    archive_command: ($) => seq(k($, 'archive'), 'audit', 'through', expr($, 'through', '_add_e'), 'to', field('path', $.text)),
    key_command: ($) => choice(
      seq(k($, 'rotate'), 'key', 'kek', field('path', $.text)),
      seq(k($, 'rotate'), 'key', 'dek'),
      seq(k($, 'destroy'), 'key', 'dek', field('id', $.int)),
    ),
    dump_command: ($) => prec.right(seq(k($, 'dump'), 'to', field('path', $.text), optional(seq(k($, 'encrypt'), expr($, 'key', '_prefix_e'))))),
    restore_command: ($) => prec.right(seq(
      k($, 'restore'),
      'from',
      field('from', $.text),
      'to',
      field('to', $.text),
      optional(choice(
        seq(k($, 'before'), 'version', field('version', $.int)),
        seq(k($, 'at_restore'), choice('instant', 'position'), expr($, 'point', '_add_e')),
      )),
    )),
    backup_command: ($) => prec.right(seq(k($, 'backup'), 'to', field('path', $.text), optional(k($, 'incremental')))),

    _write: ($) => choice($._plain_write, $.write_sequence, $.write_if, $.write_match),
    _plain_write: ($) => choice($.insert, $.update, $.delete, $.fail, alias('skip', $.skip)),
    fail: ($) => seq('fail', expr($, 'value', '_or_e')),
    insert: ($) => prec.right(seq(
      'insert',
      field('target', $.relation_ref),
      optional(k($, 'insert_from')),
      expr($, 'source', '_or_e'),
      optional($.upsert),
      optional(seq(k($, 'rejects'), 'into', field('rejects', $._qlower))),
    )),
    upsert: ($) => seq(
      k($, 'unless'),
      'conflict',
      'on',
      choice('key', seq($.index_fields, optional($.scope))),
      'else',
      field('otherwise', $._write),
    ),
    update: ($) => seq(
      'update',
      field('binder', $.lower),
      optional(seq('in', expr($, 'source', '_or_e'))),
      optional(seq('where', expr($, 'filter'))),
      'set',
      expr($, 'value'),
    ),
    delete: ($) => prec.right(seq(
      'delete',
      field('binder', $.lower),
      optional(seq('in', expr($, 'source', '_or_e'))),
      optional(seq('where', expr($, 'filter'))),
    )),
    write_sequence: ($) => seq('(', commaSep1($._write), ')'),
    write_if: ($) => prec.right(seq(
      'if',
      expr($, 'condition'),
      'then',
      field('consequence', $._write),
      'else',
      field('alternative', $._write),
    )),
    write_match: ($) => prec.right(seq('match', expr($, 'scrutinee', '_or_e'), repeat1($.write_arm))),
    write_arm: ($) => prec.right(seq($._arm_bar, '|', $._arm_head, field('body', $._write))),

    transact_block: ($) => prec.right(seq(
      'transact',
      repeat($._transact_option),
      repeat(choice($.let_binding, $._write)),
      optional(seq('return', expr($, 'return'))),
    )),
    _transact_option: ($) => choice(
      seq(k($, 'retry'), field('retry', $.int)),
      seq(k($, 'read_only'), optional(k($, 'deferrable'))),
      seq(k($, 'durability'), choice('quorum', 'local')),
    ),
    let_binding: ($) => seq('let', field('name', $.lower), '=', choice(field('value', $._write), expr($, 'value'))),

    // Expressions, from the loosest level to the tightest. A position holding an expression closes it
    // with the zero width `_end`.
    _expression: ($) => choice(alias($._union_bin, $.binary_expression), $._or_e),
    _union_bin: ($) => prec.left(seq(field('left', $._expression), $._union_op, field('operator', 'union'), field('right', $._or_e))),
    _or_e: ($) => choice(alias($._or_bin, $.binary_expression), $._and_e),
    _or_bin: ($) => prec.left(seq(field('left', $._or_e), $._or_op, field('operator', 'or'), field('right', $._and_e))),
    _and_e: ($) => choice(alias($._and_bin, $.binary_expression), $._not_e),
    _and_bin: ($) => prec.left(seq(field('left', $._and_e), $._and_op, field('operator', 'and'), field('right', $._not_e))),
    _not_e: ($) => choice($.not_expression, $._cmp_e),
    not_expression: ($) => seq('not', field('operand', $._not_e)),
    _cmp_e: ($) => choice(alias($._cmp_bin, $.binary_expression), $._add_e),
    _cmp_bin: ($) => seq(field('left', $._add_e), $._cmp_op, field('operator', choice('==', '!=', '<', '<=', '>', '>=')), field('right', $._add_e)),
    _add_e: ($) => choice(alias($._add_bin, $.binary_expression), $._mul_e),
    _add_bin: ($) => prec.left(seq(field('left', $._add_e), $._add_op, field('operator', choice('+', '-', '++')), field('right', $._mul_e))),
    _mul_e: ($) => choice(alias($._mul_bin, $.binary_expression), $._prefix_e),
    _mul_bin: ($) => prec.left(seq(field('left', $._mul_e), $._mul_op, field('operator', choice('*', '/', '%')), field('right', $._prefix_e))),
    _prefix_e: ($) => choice($.prefix_expression, $._postfix_e),
    prefix_expression: ($) => seq(field('operator', choice('-', 'key', 'try')), field('operand', $._prefix_e)),
    _postfix_e: ($) => choice(
      $.field_expression,
      $.selection_expression,
      $.key_call,
      $.backlink_expression,
      $._primary,
      seq($._postfix_e, $._field_call_bad, $._never),
    ),
    field_expression: ($) => seq(field('value', $._postfix_e), $._field_dot, '.', field('field', $.field_name)),
    selection_expression: ($) => seq(field('value', $._postfix_e), $._selection_dot, '.', field('selection', $.ctor_selection)),
    key_call: ($) => seq(field('value', $._postfix_e), $._key_dot, '.', 'key', '(', choice(field('arguments', $.named_arguments), expr($, 'arguments')), ')'),
    named_arguments: ($) => commaSep1($.named_argument),
    named_argument: ($) => seq(field('name', $.field_name), $._field_colon, ':', expr($, 'value')),
    backlink_expression: ($) => seq(
      field('value', $._postfix_e),
      $._backlink_dot,
      '.<',
      field('relation', $._qlower),
      optional(seq('.', field('selection', $.ctor_selection))),
      '.',
      field('field', $.field_name),
    ),

    _primary: ($) => choice(
      $.int,
      $.decimal,
      $.float,
      $.text,
      $.duration,
      $.boolean,
      $.comprehension,
      $.match_expression,
      $.fix_expression,
      $.lambda,
      $.exists_expression,
      $.top_expression,
      $.if_expression,
      $.at_expression,
      $.reject_expression,
      $.name,
      $.call,
      $.constructor_expression,
      $.type_call,
      $.record_expression,
      $.set_literal,
      $.unit,
      $.write_sequence,
      $.parenthesized_expression,
      $.elision,
    ),
    boolean: () => choice('true', 'false'),
    unit: () => seq('(', ')'),
    elision: ($) => seq($._elision_dot, '.', '.', '.'),
    parenthesized_expression: ($) => seq('(', expr($), ')'),
    name: ($) => $._qlower,

    call: ($) => prec.right(seq(
      field('function', choice($._qlower, $._qupper)),
      $._call_lparen,
      '(',
      $._call_body,
      optional($.pins),
    )),
    pins: ($) => seq(k($, 'pins'), $.version),
    _call_body: ($) => seq(optional(field('arguments', choice($.aggregate_arguments, $.arguments))), ')'),
    arguments: ($) => commaSep1(expr($)),
    aggregate_arguments: ($) => seq(
      expr($, 'value'),
      'for',
      $._generators,
      optional(seq('where', expr($, 'filter'))),
    ),
    constructor_expression: ($) => prec.right(seq(
      field('name', $._qupper),
      optional(seq($._ctor_dot, '.', field('constructor', $.upper))),
      optional(field('record', alias($._ctor_record, $.record_expression))),
    )),
    type_call: ($) => choice(
      seq(field('type', $._qupper), $._tcall_dot, '.', field('function', $.lower), $._call_lparen, '(', $._call_body),
      seq($._tcall_lparen, '(', field('type', $._type), ')', '.', field('function', $.lower), $._call_lparen, '(', $._call_body),
    ),
    _ctor_record: ($) => seq($._ctor_lbrace, '{', $._record_body),
    record_expression: ($) => seq('{', $._record_body),
    _record_body: ($) => choice(
      '}',
      seq($._record_elision, '.', '.', optional('.'), '}'),
      seq(commaSep1($.field_initializer), '}'),
      seq(expr($, 'base'), 'with', commaSep1($.field_initializer), '}'),
    ),
    field_initializer: ($) => seq(field('name', $.field_name), $._field_colon, ':', expr($, 'value')),
    set_literal: ($) => seq('[', commaSep(expr($)), ']'),

    _generators: ($) => prec.right(seq($.generator, repeat(seq($._gen_comma, ',', $.generator)))),
    generator: ($) => seq(field('binder', $.lower), 'in', expr($, 'source', '_or_e')),
    from_clause: ($) => seq('from', $._generators),
    where_clause: ($) => seq('where', expr($, 'filter')),
    group_clause: ($) => seq('group', expr($, 'value', '_or_e'), 'by', expr($, 'by', '_or_e'), 'into', field('into', $.lower)),
    comprehension: ($) => prec.right(seq(
      $.from_clause,
      repeat(choice($.from_clause, $.where_clause)),
      optional(seq($.group_clause, repeat(choice($.from_clause, $.where_clause)))),
      'select',
      expr($, 'select'),
      optional($.order_clause),
    )),
    order_clause: ($) => prec.right(seq(
      k($, 'order'),
      'by',
      $._order_keys,
      optional(seq(k($, 'take'), expr($, 'take', '_add_e'), optional(seq(k($, 'after'), expr($, 'after', '_add_e'))))),
    )),
    _order_keys: ($) => choice(seq($._keys_lparen, '(', commaSep1($.order_key), ')'), $.order_key),
    order_key: ($) => prec.right(seq(expr($, 'value', '_add_e'), optional(choice(k($, 'desc'), k($, 'asc'))))),
    top_expression: ($) => seq('top', expr($, 'count', '_add_e'), 'by', $._order_keys, '(', field('body', $.comprehension), ')'),

    match_expression: ($) => prec.right(seq('match', expr($, 'scrutinee', '_or_e'), $._arms)),
    _arms: ($) => prec.right(repeat1($.arm)),
    arm: ($) => seq($._arm_bar, '|', $._arm_head, expr($, 'body')),
    _arm_head: ($) => seq(
      field('pattern', $._pattern),
      repeat(seq('|', field('pattern', $._pattern))),
      optional(seq('if', expr($, 'guard'))),
      '->',
    ),
    _pattern: ($) => choice(
      $.wildcard,
      alias($.lower, $.binding),
      $.constructor_pattern,
      alias(choice('true', 'false'), $.boolean),
      $.literal_pattern,
    ),
    constructor_pattern: ($) => prec.right(seq(
      field('name', $._qupper),
      optional(seq('.', field('constructor', $.upper))),
      optional(field('payload', choice($.wildcard, alias($.lower, $.binding), $.record_pattern))),
    )),
    record_pattern: ($) => seq('{', commaSep($.field_pattern), '}'),
    field_pattern: ($) => seq(field('name', $.field_name), optional(seq(':', field('pattern', $._pattern)))),
    literal_pattern: ($) => choice(
      seq(optional('-'), choice($.int, $.decimal, $.float)),
      $.text,
    ),

    fix_expression: ($) => seq('fix', commaSep1($.fix_binding), 'in', expr($, 'body')),
    fix_binding: ($) => seq(field('name', $.lower), '=', expr($, 'value')),
    lambda: ($) => seq('fn', field('parameters', choice($.parameters, alias($.lower, $.binding))), '->', expr($, 'body')),
    exists_expression: ($) => prec.right(seq('exists', $._generators, optional(seq(k($, 'exists_where'), expr($, 'filter'))))),
    if_expression: ($) => seq(
      'if',
      expr($, 'condition'),
      'then',
      expr($, 'consequence'),
      'else',
      expr($, 'alternative'),
    ),
    at_expression: ($) => seq(
      k($, 'at'),
      choice('commit', 'instant'),
      expr($, 'point', '_add_e'),
      optional($.pins),
      '{',
      expr($, 'body'),
      '}',
    ),
    reject_expression: ($) => seq(k($, 'reject'), expr($, 'value')),
  },
});
